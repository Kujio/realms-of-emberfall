#!/usr/bin/env python3
"""Copy the display content the client needs into client/data/ (the client's bundled content copy).

Writes client/data/visuals.json from content/models.json, content/appearance.json, the class armour
types of content/classes.json and the visual ids and chest outfits of content/items.json, and client/data/items.json (every item's display data: name, slots, stats,
restrictions, value, plus the names and descriptions of item effects) for tooltips and windows, and client/data/crafts.json (the
tradeskills and recipes, Phase 13) for the station window. The server stays authoritative for gameplay; this file only tells the
client how things look. CI runs `--check`, which fails if the committed copy is stale.

Usage: python tools/sync_client_content.py [--check]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
OUT = ROOT / "client" / "data" / "visuals.json"
ITEMS_OUT = ROOT / "client" / "data" / "items.json"
ZONES_OUT = ROOT / "client" / "data" / "zones"
WORLD_OUT = ROOT / "client" / "data" / "world.json"
ENV_OUT = ROOT / "client" / "data" / "environments.json"
FX_OUT = ROOT / "client" / "data" / "effects.json"
SOUNDS_OUT = ROOT / "client" / "data" / "sounds.json"
CREDITS_OUT = ROOT / "client" / "data" / "credits.json"
CRAFTS_OUT = ROOT / "client" / "data" / "crafts.json"


def strip_comments(v):
    if isinstance(v, dict):
        return {k: strip_comments(x) for k, x in v.items() if k != "_comment"}
    if isinstance(v, list):
        return [strip_comments(x) for x in v]
    return v


def outfits(items: list, tiers: dict) -> dict:
    """Chest armour as the outfit it puts on a player model: its armour type and its tier tint."""
    steps = sorted((t for t in tiers.get("tiers", []) if isinstance(t, dict)), key=lambda t: t.get("min_level", 0))
    out = {}
    for it in items:
        if not isinstance(it, dict) or "chest" not in (it.get("slots") or []) or not it.get("armor"):
            continue
        tint = ""
        for t in steps:
            if it.get("req_level", 1) >= t.get("min_level", 0):
                tint = t.get("tint", "")
        if it.get("rarity") == "epic" and tiers.get("epic"):
            tint = tiers["epic"]
        out[it["id"]] = {"armor": it["armor"], "tint": tint}
    return out


def render() -> str:
    def read(name: str) -> dict:
        return json.loads((CONTENT / name).read_text(encoding="utf-8"))

    models = strip_comments(read("models.json"))
    appearance = strip_comments(read("appearance.json"))
    items = read("items.json").get("items", [])
    classes = read("classes.json").get("classes", [])
    doc = {
        "_comment": "GENERATED by tools/sync_client_content.py from content/models.json, appearance.json and items.json. Do not edit.",
        "models": {m["id"]: m for m in models.get("models", [])},
        "animation_maps": {a["id"]: a for a in models.get("animation_maps", [])},
        "item_visuals": {v["id"]: v for v in models.get("item_visuals", [])},
        "races": {r["race"]: r for r in appearance.get("races", [])},
        "classes": {c["class"]: c for c in appearance.get("classes", [])},
        "item_visual_of": {it["id"]: it["visual"] for it in items if isinstance(it, dict) and it.get("visual")},
        "class_armor": {c["id"]: c["armor"] for c in classes if isinstance(c, dict) and c.get("armor")},
        "outfit_of": outfits(items, appearance.get("armor_tiers", {})),
        "outfit_tint": {k: v for k, v in appearance.get("armor_tiers", {}).items() if k in ("prefix", "keep")},
    }
    return json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def render_items() -> str:
    items = json.loads((CONTENT / "items.json").read_text(encoding="utf-8")).get("items", [])
    effects = json.loads((CONTENT / "item_effects.json").read_text(encoding="utf-8")).get("effects", [])
    rows = []
    for it in items:
        if not isinstance(it, dict):
            continue
        row = {k: v for k, v in it.items() if k not in ("_comment", "visual")}
        rows.append(f'  {json.dumps(it["id"])}: {json.dumps(row, sort_keys=True, ensure_ascii=False)}')
    fx = [f'  {json.dumps(e["id"])}: {json.dumps({"name": e.get("name", ""), "description": e.get("description", "")}, sort_keys=True, ensure_ascii=False)}'
          for e in effects if isinstance(e, dict)]
    return ("{\n" + '"_comment": "GENERATED by tools/sync_client_content.py from content/items.json and item_effects.json. Do not edit.",\n'
            + '"items": {\n' + ",\n".join(rows) + '\n},\n"effects": {\n' + ",\n".join(fx) + "\n}\n}\n")


def zone_docs() -> list[dict]:
    """Every zone file with its scene export merged in, in the order the server merges them."""
    sys.path.insert(0, str(ROOT / "tools"))
    zones = []
    for path in sorted((CONTENT / "zones").glob("*.json")):
        z = strip_comments(json.loads(path.read_text(encoding="utf-8")))
        scene = CONTENT / "zones" / "scenes" / path.name
        if scene.exists():
            sj = json.loads(scene.read_text(encoding="utf-8"))
            for key in ("obstacles", "walls", "zone_lines", "entries"):
                if sj.get(key):
                    z[key] = list(z.get(key, [])) + sj[key]
        z.pop("spawns", None)  # the server's business
        zones.append(z)
    return zones


def render_zones() -> list[tuple[Path, str]]:
    from zone_format import format_zone
    out = []
    for z in zone_docs():
        z = {"_comment": "GENERATED by tools/sync_client_content.py from content/zones (and its scene export). Do not edit.", **z}
        out.append((ZONES_OUT / f"{z['id']}.json", format_zone(z)))
    return out


def render_world() -> str:
    """The world map's index: zones, their bands and links, cities and travel points."""
    cities = json.loads((CONTENT / "cities.json").read_text(encoding="utf-8")).get("cities", [])
    travel = json.loads((CONTENT / "travel.json").read_text(encoding="utf-8")).get("points", [])
    zones = []
    docs = list(zone_docs())
    for z in docs:
        entry = {"id": z["id"], "name": z["name"], "kind": z.get("kind", "outdoor"), "levels": z.get("levels", {}),
                 "description": z.get("description", ""),
                 "links": sorted({l["to"] for l in z.get("zone_lines", [])})}
        if isinstance(z.get("map"), dict):
            entry["map"] = {"x": z["map"]["x"], "y": z["map"]["y"]}
        zones.append(entry)
    # Phase 12: a dungeon is drawn inside the cell of the zone its entrance is in, where the entrance is.
    by_id = {e["id"]: e for e in zones}
    for z in docs:
        b = z.get("bounds")
        if "map" not in by_id[z["id"]] or not b:
            continue
        for l in z.get("zone_lines", []):
            d = by_id.get(l["to"])
            if not d or d["kind"] != "dungeon" or "map" in d:
                continue
            fx = (l["x"] - b["min_x"]) / max(1.0, b["max_x"] - b["min_x"])
            fz = (l["z"] - b["min_z"]) / max(1.0, b["max_z"] - b["min_z"])
            d["map"] = {"in": z["id"], "fx": round(min(max(fx, 0.0), 1.0), 3), "fz": round(min(max(fz, 0.0), 1.0), 3)}
    doc = {"_comment": "GENERATED by tools/sync_client_content.py: the world map index. Do not edit.",
           "zones": zones, "cities": [{k: c[k] for k in ("id", "name", "zone", "spawn")} for c in cities],
           "travel": travel}
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def render_environments() -> str:
    """Per-biome lighting, ground clutter and dungeon decorations (content/environments.json)."""
    doc = strip_comments(json.loads((CONTENT / "environments.json").read_text(encoding="utf-8")))
    doc = {"_comment": "GENERATED by tools/sync_client_content.py from content/environments.json. Do not edit.", **doc}
    return json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def render_effects() -> str:
    """The effect library (content/effects.json) plus each spell's and ability's type and school by name,
    since combat events name the ability, not its id."""
    doc = strip_comments(json.loads((CONTENT / "effects.json").read_text(encoding="utf-8")))
    spells = json.loads((CONTENT / "spells.json").read_text(encoding="utf-8")).get("spells", [])
    abilities = json.loads((CONTENT / "abilities.json").read_text(encoding="utf-8")).get("abilities", [])
    by_name: dict[str, dict] = {}
    for a in abilities + spells:  # spells last: a spell and an ability of the same name, the spell wins
        if isinstance(a, dict) and a.get("name"):
            by_name[a["name"]] = {"type": a.get("type", ""), "school": a.get("resist", "none"), **({"song": True} if a.get("song") else {})}
    doc = {"_comment": "GENERATED by tools/sync_client_content.py from content/effects.json, spells.json and abilities.json. Do not edit.",
           **doc, "by_name": by_name}
    return json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def render_sounds() -> str:
    """Sounds and music (content/audio.json) plus every boss by name, and whether it is a raid boss,
    since the client knows a mob by its name."""
    doc = strip_comments(json.loads((CONTENT / "audio.json").read_text(encoding="utf-8")))
    mobs = json.loads((CONTENT / "mobs.json").read_text(encoding="utf-8")).get("mobs", [])
    raids, raid_spawned = set(), set()
    for zf in sorted((CONTENT / "zones").glob("*.json")):
        z = json.loads(zf.read_text(encoding="utf-8"))
        if z.get("raid"):
            raids.add(z.get("id"))
            raid_spawned |= {s.get("mob") for s in z.get("spawns", []) if isinstance(s, dict)}
    # A raid boss: its template names a raid zone, or a raid zone spawns it.
    bosses = {m["name"]: m.get("dungeon") in raids or m.get("id") in raid_spawned
              for m in mobs if isinstance(m, dict) and m.get("boss")}
    doc = {"_comment": "GENERATED by tools/sync_client_content.py from content/audio.json and mobs.json. Do not edit.",
           **doc, "bosses": bosses}
    return json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def render_credits() -> str:
    """The in-game Credits screen's data: every row of ASSETS.md's "In the build" table, each model's
    credit line from the packs' LICENSE.txt files (Polyfork asks for one per model), and the licence
    texts in LICENSES/."""
    import re
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from visual_checks import build_table_rows  # the validator's parser: the two never disagree

    def plain(s: str) -> str:
        return re.sub(r"`([^`]*)`", r"\1", s)

    rows = [{"asset": plain(c[0]), "author": plain(c[2]), "source": plain(c[3]), "license": plain(c[4])}
            for c in build_table_rows((ROOT / "ASSETS.md").read_text(encoding="utf-8"))]
    credits = []
    for lic in sorted((ROOT / "client" / "assets").rglob("LICENSE.txt")):
        for line in lic.read_text(encoding="utf-8").splitlines():
            m = re.match(r"\s+(.+? by Polyfork, CC BY 4\.0)\s+\((\S+),\s+(https://\S+)\)$", line)
            if m:
                credits.append(f"{m.group(1)}  ({m.group(3)})")
    licenses = {p.stem: p.read_text(encoding="utf-8") for p in sorted((ROOT / "LICENSES").glob("*.txt"))}
    doc = {"_comment": "GENERATED by tools/sync_client_content.py from ASSETS.md, the asset packs' LICENSE.txt files and LICENSES/. Do not edit.",
           "intro": "An original fantasy MMORPG, built as an experiment with Claude Code. Made with Godot Engine (MIT licence; see Godot-LICENSE and Godot-COPYRIGHT below).",
           "assets": rows, "model_credits": credits, "licenses": licenses}
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def render_crafts() -> str:
    """Phase 13: the tradeskills, their rules and every recipe (content/crafts.json), for the station window."""
    doc = strip_comments(json.loads((CONTENT / "crafts.json").read_text(encoding="utf-8")))
    lines = ["{", '"_comment": "GENERATED by tools/sync_client_content.py from content/crafts.json. Do not edit.",',
             '"rules": ' + json.dumps(doc["rules"]) + ",", '"tradeskills": [']
    lines += [json.dumps(t) + ("," if i < len(doc["tradeskills"]) - 1 else "") for i, t in enumerate(doc["tradeskills"])]
    lines += ["],", '"recipes": [']
    lines += [json.dumps(r) + ("," if i < len(doc["recipes"]) - 1 else "") for i, r in enumerate(doc["recipes"])]
    lines += ["]", "}", ""]
    return "\n".join(lines)


def main() -> int:
    outputs = ((OUT, render()), (ITEMS_OUT, render_items()), (WORLD_OUT, render_world()), (ENV_OUT, render_environments()),
               (FX_OUT, render_effects()), (SOUNDS_OUT, render_sounds()), (CREDITS_OUT, render_credits()), (CRAFTS_OUT, render_crafts()),
               *render_zones())
    if ZONES_OUT.exists() and "--check" in sys.argv[1:]:
        expected = {o.name for o, _ in render_zones()}
        extra = [p for p in ZONES_OUT.glob("*.json") if p.name not in expected]
        for e in extra:
            print(f"{e.relative_to(ROOT)} has no zone in content/zones: run python tools/sync_client_content.py", file=sys.stderr)
        if extra:
            return 1
    if "--check" in sys.argv[1:]:
        stale = [o for o, text in outputs if not o.exists() or o.read_text(encoding="utf-8") != text]
        for o in stale:
            print(f"{o.relative_to(ROOT)} is stale: run python tools/sync_client_content.py", file=sys.stderr)
        if stale:
            return 1
        print("client content copies are up to date")
        return 0
    if ZONES_OUT.exists():
        expected = {o.name for o, _ in render_zones()}
        for p in ZONES_OUT.glob("*.json"):
            if p.name not in expected:
                p.unlink()
    for o, text in outputs:
        json.loads(text)
        o.parent.mkdir(parents=True, exist_ok=True)
        with o.open("w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {o.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
