def apply(rows: list[dict], picks: dict[str, str], key: str) -> list[dict]:
    """Sets each row's model from `picks` (looked up by the row's `key`); returns the rows."""
    for r in rows:
        m = picks.get(r.get(key, ""))
        if m:
            r["model"] = m
    return rows
